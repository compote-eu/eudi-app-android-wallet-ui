// PROVISIONAL (M1b) test fixture: the boundary bundle, embedded as a Kotlin string under build/, so the
// tracked :ux-runtime sources carry no screen id (KC1 guard, SPIKE-PLAN §3) and there is one copy of the
// fixture. The task refuses a bundle whose sha256 is not the one the boundary names. M6 replaces it.
abstract class ProvisionalBundleFixture : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val bundle: RegularFileProperty

    @get:Input
    abstract val expectedSha256: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val bytes = bundle.get().asFile.readBytes()
        val sha = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
        check(sha == expectedSha256.get()) { "PROVISIONAL bundle sha256 is $sha, expected ${expectedSha256.get()}" }
        val text = bytes.decodeToString()
        check('$' !in text && "\"\"\"" !in text) { "the bundle cannot be embedded in a raw string" }
        val chunks = mutableListOf(StringBuilder())
        text.lineSequence().forEach { line ->
            if (chunks.last().length > CHUNK) chunks += StringBuilder()
            chunks.last().append(line).append('\n')
        }
        val q = "\"\"\""
        val body = chunks.joinToString(",\n") { "        $q$it$q" }
        val dir = outputDir.get().asFile.resolve("eu/europa/ec/ux/runtime/fixture").apply { mkdirs() }
        dir.resolve("ProvisionalPresBundle.kt").writeText(
            """
            |// PROVISIONAL (M1b): generated by :ux-runtime:provisionalBundleFixture from
            |// spike-evidence/boundary/FLW-pres-cross-device.bundle.PROVISIONAL.json (sha256 $sha). Do not edit.
            |package eu.europa.ec.ux.runtime.fixture
            |
            |internal object ProvisionalPresBundle {
            |    const val SHA256: String = "$sha"
            |    val JSON: String = listOf(
            |$body
            |    ).joinToString("")
            |}
            |""".trimMargin()
        )
    }

    private companion object {
        const val CHUNK = 16_000
    }
}

val provisionalFixture = tasks.register<ProvisionalBundleFixture>("provisionalBundleFixture") {
    bundle.set(rootProject.layout.projectDirectory.file("spike-evidence/boundary/FLW-pres-cross-device.bundle.PROVISIONAL.json"))
    expectedSha256.set("31bfda6579b2a388de96e4a52a618362c53b18b883a1ab239f6856c0dbcf8d71")
    outputDir.set(layout.buildDirectory.dir("generated/provisional-fixture/kotlin"))
}

